#!/usr/bin/env node
// Render the always-on router from core/harness/ and install it.
// Usage:
//   node scripts/sync-harnesses.mjs --repo [--check]
//   node scripts/sync-harnesses.mjs --print-router <repo|project|global> [--home DIR]
//   node scripts/sync-harnesses.mjs --project <path> [--dry-run]
//   node scripts/sync-harnesses.mjs --global [--home DIR] [--dry-run]
import { existsSync, readFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { CORE, HARNESS_ROOT, isMain, resolveUserPath, toPosix } from "./lib/paths.mjs";
import {
  AGENTS_IMPORT, homeFor, isManaged, renderBlock, renderOwnedMdc, spliceBlock, wrapBlock,
} from "./lib/managed-blocks.mjs";
import { detectStack, fillTokens, renderProjectJson, templateTokens } from "./lib/detect-stack.mjs";
import { Installer, collectFiles, requireFiles } from "./lib/install-tree.mjs";

const TREE_DIRS = ["playbooks", "principles", "skills", "prompts", "templates"].map((dir) => `${CORE}/${dir}`);
const HARNESS_FILES = ["manifest.json", "routes.json", "router.md"].map((file) => `${CORE}/harness/${file}`);
const LEGAL_FILES = ["LICENSE", "docs/THIRD_PARTY_NOTICES.md"];
const MDC_PATH = ".cursor/rules/poteto-harness.mdc";
// Repository-only tooling: it needs docs/, install.sh, package.json or scripts/tests/, which a
// global home does not hold, so it is not copied there.
const REPO_ONLY_SCRIPTS = new Set([
  "scripts/check-install.mjs", "scripts/validate-harness.mjs", "scripts/run-autonomous-smoke-test.mjs", "scripts/run-tests.mjs",
]);

export const REPO_AGENTS_TOP = `# poteto-harness

This repository is the harness itself. The router block below is generated from \`core/harness/\`; edit the sources, never the block.

| Task | Command |
|---|---|
| Validate everything | \`node scripts/validate-harness.mjs\` |
| Unit tests | \`node scripts/run-tests.mjs\` |
| Regenerate router files | \`node scripts/sync-harnesses.mjs --repo\` |
| Prove install idempotency | \`node scripts/check-install.mjs\` |
| Autonomous smoke test | \`node scripts/run-autonomous-smoke-test.mjs\` |
`;

export const REPO_CLAUDE = `<!-- Generated by scripts/sync-harnesses.mjs: Claude Code loads the poteto-harness router through this import. -->

@AGENTS.md
`;

const read = (abs) => readFileSync(abs, "utf8");
const readIf = (abs) => (existsSync(abs) ? read(abs) : null);

// ---- repo mode -------------------------------------------------------------

// The repository AGENTS.md is fully generated: REPO_AGENTS_TOP, then the router block.
export function repoOutputs(root = HARNESS_ROOT) {
  const block = renderBlock(homeFor("repo"), root);
  return [
    ["AGENTS.md", spliceBlock(REPO_AGENTS_TOP, block)],
    ["CLAUDE.md", REPO_CLAUDE],
    [MDC_PATH, renderOwnedMdc(block)],
  ];
}

function runRepo({ check }) {
  const outputs = repoOutputs();
  if (check) {
    const drifted = outputs.filter(([rel, text]) => readIf(path.join(HARNESS_ROOT, rel)) !== text).map(([rel]) => rel);
    for (const rel of drifted) console.log(`drift     ${rel}`);
    console.log(`poteto-harness: repo-check ${toPosix(HARNESS_ROOT)} drifted=${drifted.length}`);
    if (drifted.length) console.log("Run: node scripts/sync-harnesses.mjs --repo");
    return drifted.length ? 1 : 0;
  }
  const inst = new Installer({ root: HARNESS_ROOT });
  for (const [rel, text] of outputs) inst.writeIfDifferent(path.join(HARNESS_ROOT, rel), text);
  console.log(`poteto-harness: repo ${toPosix(HARNESS_ROOT)} writes=${inst.writes}`);
  return 0;
}

// ---- shared install steps --------------------------------------------------

// Every user-file write is computed before anything is written, so a file the splice refuses
// (broken markers) or an unreadable package.json stops the install with nothing on disk.
const planSplice = (abs, block, fallback = "") => ({ abs, text: spliceBlock(readIf(abs) ?? fallback, block) });

function planOwnedMdc(abs, block) {
  const existing = readIf(abs);
  if (existing !== null && !isManaged(existing)) return { abs, skip: "(not managed)" };
  return { abs, text: renderOwnedMdc(block) };
}

function applyPlan(inst, plan) {
  for (const step of plan) {
    if (step.skip) inst.log("skip", step.abs, step.skip);
    else if (step.unchanged) inst.log("unchanged", step.abs, step.unchanged);
    else inst.writeIfDifferent(step.abs, step.text);
  }
}

function templateText(rel) {
  return read(path.join(HARNESS_ROOT, CORE, "templates", rel));
}

function utcDate(now = new Date()) {
  return now.toISOString().slice(0, 10);
}

function readManifest() {
  return JSON.parse(read(path.join(HARNESS_ROOT, CORE, "harness", "manifest.json")));
}

// ---- project mode ----------------------------------------------------------

export function projectEntries() {
  const manifest = readManifest();
  const scripts = manifest.projectScripts.map((s) => `scripts/${s}`);
  return [
    ...requireFiles(HARNESS_ROOT, [...HARNESS_FILES, ...scripts, ...LEGAL_FILES]),
    ...collectFiles(HARNESS_ROOT, TREE_DIRS),
  ];
}

export function installProject(target, { dryRun = false, out } = {}) {
  const root = path.resolve(target);
  if (root === path.resolve(HARNESS_ROOT)) throw new Error("the target is the harness repo itself; use --repo");
  const entries = projectEntries();
  const inst = new Installer({ root, dryRun, out });
  const home = path.join(root, ".poteto");

  const stack = detectStack(root);
  const tokens = templateTokens(stack, utcDate());
  const fill = (rel) => fillTokens(templateText(rel), tokens);
  const block = renderBlock(homeFor("project"));
  const claudePath = path.join(root, "CLAUDE.md");
  const claude = readIf(claudePath);
  const plan = [
    planSplice(path.join(root, "AGENTS.md"), block, fill("AGENTS.project.md.template")),
    claude === null ? { abs: claudePath, text: fill("CLAUDE.md.template") }
      : AGENTS_IMPORT.test(claude) ? { abs: claudePath, unchanged: "(already imports @AGENTS.md)" }
        : planSplice(claudePath, wrapBlock("@AGENTS.md")),
    planOwnedMdc(path.join(root, MDC_PATH), block),
  ];

  inst.copyTree(entries, home);
  inst.writeIfDifferent(path.join(home, "project.json"), renderProjectJson(stack));
  inst.createIfMissing(path.join(home, "decisions.tsv"), templateText("poteto/decisions.tsv"));
  inst.createIfMissing(path.join(home, "corrections.md"), fill("poteto/corrections.md.template"));
  applyPlan(inst, plan);

  inst.createIfMissing(path.join(root, "PRODUCT.md"), fill("PRODUCT.md.template"));
  for (const doc of readManifest().docs) {
    inst.createIfMissing(path.join(root, "docs", doc), fill(`docs/${doc}.template`));
  }
  return inst;
}

// ---- global mode -----------------------------------------------------------

export function globalEntries() {
  return [
    ...collectFiles(HARNESS_ROOT, [...TREE_DIRS, `${CORE}/harness`, "scripts"], { exclude: ["tests", "smoke", "node_modules"] })
      .filter((e) => !REPO_ONLY_SCRIPTS.has(e.rel)),
    ...requireFiles(HARNESS_ROOT, LEGAL_FILES),
  ];
}

// codexHome: where Codex reads its global AGENTS.md (CODEX_HOME); defaults to <home>/.codex.
export function installGlobal(homeDir, { dryRun = false, out, codexHome = null } = {}) {
  const root = path.resolve(homeDir);
  const codexDir = codexHome ? path.resolve(codexHome) : path.join(root, ".codex");
  const entries = globalEntries();
  const manifest = readManifest();
  const missing = manifest.projectScripts.filter((s) => !entries.some((e) => e.rel === `scripts/${s}`));
  if (missing.length) throw new Error(`harness source is incomplete; missing scripts: ${missing.join(", ")}`);
  const inst = new Installer({ root, dryRun, out });
  const harnessHome = path.join(root, ".poteto-harness");
  const block = renderBlock(homeFor("global", root));
  const plan = [
    planSplice(path.join(root, ".claude", "CLAUDE.md"), block),
    planSplice(path.join(codexDir, "AGENTS.md"), block),
    planOwnedMdc(path.join(root, MDC_PATH), block),
  ];
  if (path.resolve(harnessHome) === path.resolve(HARNESS_ROOT)) {
    inst.log("skip", harnessHome, "(running from the installed copy; files already in place)");
  } else {
    inst.copyTree(entries, harnessHome);
  }
  applyPlan(inst, plan);
  inst.out("note      Cursor may require pasting user rules in its Settings; the .mdc file is written, loading is not verified by this script.");
  return inst;
}

// ---- CLI -------------------------------------------------------------------

const USAGE = `Usage:
  node scripts/sync-harnesses.mjs --repo [--check]
  node scripts/sync-harnesses.mjs --print-router <repo|project|global> [--home DIR]
  node scripts/sync-harnesses.mjs --project <path> [--dry-run]
  node scripts/sync-harnesses.mjs --global [--home DIR] [--dry-run]`;

export function parseArgs(argv) {
  const opts = { mode: null, check: false, dryRun: false, home: null, target: null };
  const value = (i, flag) => {
    const next = argv[i + 1];
    if (!next || next.startsWith("--")) throw new Error(`${flag} needs a value`);
    return next;
  };
  const setMode = (mode) => {
    if (opts.mode) throw new Error(`choose one mode; got --${opts.mode} and --${mode}`);
    opts.mode = mode;
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--repo") setMode("repo");
    else if (arg === "--global") setMode("global");
    else if (arg === "--project") { setMode("project"); opts.target = value(i, arg); i++; }
    else if (arg === "--print-router") { setMode("print-router"); opts.target = value(i, arg); i++; }
    else if (arg === "--home") { opts.home = value(i, arg); i++; }
    else if (arg === "--check") opts.check = true;
    else if (arg === "--dry-run") opts.dryRun = true;
    else if (arg === "-h" || arg === "--help") setMode("help");
    else throw new Error(`unknown argument "${arg}"`);
  }
  if (!opts.mode) throw new Error("no mode given");
  if (opts.check && opts.mode !== "repo") throw new Error("--check only applies to --repo");
  return opts;
}

export function main(argv = process.argv.slice(2)) {
  const opts = parseArgs(argv);
  if (opts.mode === "help") {
    console.log(USAGE);
    return 0;
  }
  if (opts.mode === "repo") return runRepo(opts);
  if (opts.mode === "print-router") {
    const home = opts.target === "global" ? resolveUserPath(opts.home ?? os.homedir()) : null;
    process.stdout.write(`${renderBlock(homeFor(opts.target, home))}\n`);
    return 0;
  }
  const suffix = opts.dryRun ? " (dry-run, nothing written)" : "";
  if (opts.mode === "project") {
    const target = resolveUserPath(opts.target);
    const inst = installProject(target, { dryRun: opts.dryRun });
    console.log(`poteto-harness: project ${toPosix(target)} writes=${inst.writes}${suffix}`);
    return 0;
  }
  const home = resolveUserPath(opts.home ?? os.homedir());
  // Codex reads its global AGENTS.md from $CODEX_HOME; an explicit --home keeps everything under it.
  const codexHome = !opts.home && process.env.CODEX_HOME ? resolveUserPath(process.env.CODEX_HOME) : null;
  const inst = installGlobal(home, { dryRun: opts.dryRun, codexHome });
  console.log(`poteto-harness: global ${toPosix(home)} writes=${inst.writes}${suffix}`);
  return 0;
}

if (isMain(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (error) {
    console.error(`poteto-harness: error: ${error.message}`);
    console.error(USAGE);
    process.exitCode = 1;
  }
}
